alter table public.bccr_rates add column if not exists last_verification timestamptz;
update public.bccr_rates set
  short_name = coalesce(short_name, case code when '423' then 'TBP' when '23698' then 'TED' when '317' then 'Compra' when '318' then 'Venta' when '3541' then 'TPM' else name end),
  unit = coalesce(unit, case when code in ('317', '318') then 'CRC' else 'percent' end),
  description = coalesce(description, 'Indicador publicado por el BCCR.'),
  last_verification = coalesce(last_verification, created_at, now());
