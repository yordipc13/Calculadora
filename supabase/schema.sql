-- Official BCCR observations only. A row is added when an indicator value changes.
create table if not exists public.bccr_rates (
  id bigint generated by default as identity primary key,
  code text not null,
  name text not null,
  short_name text not null,
  currency text not null check (currency in ('CRC', 'USD')),
  unit text not null check (unit in ('percent', 'CRC')),
  description text not null,
  value numeric(14,6) not null check (value >= 0),
  reference_date date not null,
  last_verification timestamptz,
  source text not null default 'BCCR SDDE',
  created_at timestamptz not null default now(),
  unique (code, reference_date)
);
