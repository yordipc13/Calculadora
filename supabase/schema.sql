alter table public.bccr_rates add constraint bccr_rates_nonnegative_value check (value >= 0);
create index if not exists bccr_rates_code_date_idx on public.bccr_rates (code, reference_date desc);

create table if not exists public.bccr_rate_status (
  code text primary key,
  indicator_name text not null,
  last_verification timestamptz not null,
  last_success timestamptz,
  status text not null check (status in ('ok', 'error')),
  last_error text
);

create table if not exists public.bccr_job_logs (
  id bigint generated by default as identity primary key,
  code text,
  status text not null check (status in ('ok', 'error')),
  error text,
  executed_at timestamptz not null default now()
);

alter table public.bccr_rates enable row level security;
alter table public.bccr_rate_status enable row level security;
alter table public.bccr_job_logs enable row level security;

drop policy if exists "rates are public read" on public.bccr_rates;
create policy "rates are public read" on public.bccr_rates for select using (true);
drop policy if exists "rate status is public read" on public.bccr_rate_status;
create policy "rate status is public read" on public.bccr_rate_status for select using (true);
drop policy if exists "job logs are private" on public.bccr_job_logs;
create policy "job logs are private" on public.bccr_job_logs for select using (false);

grant select on public.bccr_rates, public.bccr_rate_status to anon, authenticated;
grant all on public.bccr_rates, public.bccr_rate_status, public.bccr_job_logs to service_role;
